    private JButton tombolAktif = null;

    private void aturHover() {

        JButton[] tombol = {
            btnCustomer,
            btnTransaksi,
            btnMobil,
            btnDataTransaksi,
            btnPengembalian
        };

        for (JButton item : tombol) {

            item.setBackground(java.awt.Color.BLACK);
            item.setForeground(java.awt.Color.WHITE);

            item.setFont(new java.awt.Font("Segoe UI", java.awt.Font.PLAIN, 13));

            item.setBorderPainted(false);
            item.setFocusPainted(false);
            item.setContentAreaFilled(true);
            item.setOpaque(true);
            item.setMargin(new java.awt.Insets(8, 12, 8, 12));

            item.addMouseListener(new java.awt.event.MouseAdapter() {

                @Override
                public void mouseEntered(java.awt.event.MouseEvent evt) {
                    if (item != tombolAktif) {
                        item.setBackground(new java.awt.Color(55, 55, 55));
                    }
                }

                @Override
                public void mouseExited(java.awt.event.MouseEvent evt) {
                    if (item != tombolAktif) {
                        item.setBackground(java.awt.Color.BLACK);
                    }
                }
            });
        }
    }
    
    private void setTombolAktif(JButton tombol) {

        JButton[] semuaTombol = {
            btnCustomer,
            btnTransaksi,
            btnMobil,
            btnDataTransaksi,
            btnPengembalian
        };

        for (JButton item : semuaTombol) {
            item.setBackground(java.awt.Color.BLACK);
        }

        tombolAktif = tombol;

        tombolAktif.setBackground(new java.awt.Color(65, 65, 65));
    }

    private void tampilkanHalaman() {

    CardLayout cl = new CardLayout();

    panelKonten.setLayout(cl);

    panelKonten.add(new dashboard(), "dashboard");
    panelKonten.add(new TampilanCustomer(), "customer");
    panelKonten.add(new TampilanTransaksi(), "transaksi");
    panelKonten.add(new TampilanMobil(), "mobil");
    panelKonten.add(new TampilanDataTransaksi(), "data");
    panelKonten.add(new TampilanPengembalian(), "pengembalian");

    cl.show(panelKonten, "dashboard");
    }
    
    private void pindahHalaman(String halaman) {
    CardLayout cl = (CardLayout) panelKonten.getLayout();
    cl.show(panelKonten, halaman);
    }

